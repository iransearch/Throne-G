const vpnDNSProfile = `{"dns":{"servers":[{"type":"vpn-dns-race","tag":"dns-remote","timeout":"8s","fallback_timeout":"4s","servers":[
{"type":"https","tag":"google","server":"8.8.8.8","detour":"proxy","path":"/dns-query","tls":{"enabled":true,"server_name":"dns.google"}},
{"type":"https","tag":"cloudflare","server":"1.1.1.1","detour":"proxy","path":"/dns-query","tls":{"enabled":true,"server_name":"cloudflare-dns.com"}},
{"type":"https","tag":"yandex","server":"77.88.8.8","detour":"proxy","path":"/dns-query","tls":{"enabled":true,"server_name":"common.dot.dns.yandex.net"}},
{"type":"udp","tag":"additional","server":"78.186.60.77","server_port":53,"detour":"proxy"}],
"fallback":{"type":"tcp","server":"1.1.1.1","server_port":53,"detour":"proxy"}}],
"rules":[{"action":"route","server":"dns-remote","timeout":"12s"}]},
"outbounds":[{"type":"direct","tag":"proxy"}],"route":{"auto_detect_interface":true}}`

func TestVPNDNSRegistrationAndCheck(t *testing.T) {
	contexts := []context.Context{newBoxContext(), boxbox.Context(context.Background(), include.InboundRegistry(), include.OutboundRegistry(), include.EndpointRegistry(), include.DNSTransportRegistry(), include.ServiceRegistry(), include.CertificateProviderRegistry())}
	for _, ctx := range contexts {
		var cfg option.Options
		if err := json.UnmarshalContext(ctx, []byte(vpnDNSProfile), &cfg); err != nil {
			t.Fatal(err)
		}
		if cfg.DNS.Servers[0].Type != vpndns.Type {
			t.Fatal("VPN DNS type not registered before parsing")
		}
		o := cfg.DNS.Servers[0].Options.(*vpndns.Options)
		if len(o.Servers) != 4 || o.Fallback.Type != "tcp" {
			t.Fatal("nested providers/fallback lost")
		}
	}
	if err := Check([]byte(vpnDNSProfile)); err != nil {
		t.Fatal(err)
	}
}

// Optional fixtures generated by the Windows configuration tests. Use the real
// registry/parser and Box constructor, with unrelated geo/UI routing removed.
func TestVPNDNSFixtures(t *testing.T) {
	dir := os.Getenv("IRSPEEDY_DNS_FIXTURES")
	if dir == "" {
		t.Skip("set IRSPEEDY_DNS_FIXTURES to emitted Windows fixtures")
	}
	for _, name := range []string{"proxy", "tun", "split-proxy", "split-tun", "scoped"} {
		t.Run(name, func(t *testing.T) {
			raw, err := os.ReadFile(filepath.Join(dir, name+".json"))
			if err != nil {
				t.Fatal(err)
			}
			var doc map[string]stdjson.RawMessage
			if err = stdjson.Unmarshal(raw, &doc); err != nil {
				t.Fatal(err)
			}
			profile := map[string]stdjson.RawMessage{"dns": doc["dns"],
				"outbounds": stdjson.RawMessage(`[{"type":"direct","tag":"proxy"},{"type":"direct","tag":"split-direct"}]`),
				"route":     stdjson.RawMessage(`{"auto_detect_interface":true,"default_domain_resolver":{"server":"dns-direct","strategy":"prefer_ipv4"}}`)}
			data, err := stdjson.Marshal(profile)
			if err != nil {
				t.Fatal(err)
			}
			if err = Check(data); err != nil {
				t.Fatal(err)
			}
		})
	}
}
